"""지적 문장 ↔ 조문 원문 기계 대조가 양방향으로 작동하는지 지킨다 (#78).

이 대조는 판정기 오탐을 기각한다. 느슨해지면 **진짜 날조를 기각**해 버리므로,
오탐을 기각하는 테스트와 날조를 기각하지 않는 테스트가 같이 있어야 한다.
느슨하게 고쳐 오탐만 줄이면 아래 날조 테스트가 먼저 깨진다.

실측 출처: 2026-11-10 판정 3회에서 조문 원문과 대조해 오탐으로 확인한 지적들과,
`eval/judge_negative_controls.json`의 조작 답변 지적들.
"""
import pytest

from eval.eval_hallucination import claim_evidence, recheck_case

# 중대재해처벌법 제2조·제10조, 안전보건기준규칙 제296조·제37조의 실제 문구
CONTEXTS = [
    "제2조(정의) 2. \"중대산업재해\"란 다음 각 목의 어느 하나에 해당하는 결과를 야기한 "
    "재해를 말한다. 가. 사망자가 1명 이상 발생 나. 동일한 사고로 6개월 이상 치료가 "
    "필요한 부상자가 2명 이상 발생 다. 동일한 유해요인으로 급성중독 등 대통령령으로 "
    "정하는 직업성 질병자가 1년 이내에 3명 이상 발생",
    "제10조(중대시민재해 사업주와 경영책임자등의 처벌) 1 제9조를 위반하여 제2조제3호가목의 "
    "중대시민재해에 이르게 한 사업주 또는 경영책임자등은 1년 이상의 징역 또는 10억원 "
    "이하의 벌금에 처한다. 이 경우 징역과 벌금을 병과할 수 있다.",
    "제37조(위험성평가의 방법, 절차 및 시기) 2. 정기평가: 제1호에 따른 최초평가를 실시한 "
    "연도의 다음 연도부터 매년 1회 이상",
]


# ── 오탐: 지적 문장이 조문에 그대로 있다 → 기각돼야 한다 ──
@pytest.mark.parametrize("claim", [
    # GS-021 — 다섯 조문 중 첫 조문의 각 목 중간에 그대로 있었다
    "동일한 사고로 6개월 이상 치료가 필요한 부상자가 2명 이상 발생",
    # GS-024 — 제10조 본문을 그대로 옮긴 문장 (교차 참조 '제9조' 포함)
    "제9조를 위반하여 제2조제3호가목의 중대시민재해에 이르게 한 사업주 또는 경영책임자는 "
    "1년 이상의 징역 또는 10억원 이하의 벌금에 처하며, 이 경우 징역과 벌금을 병과할 수 있습니다.",
    # GS-004 — 짧아서 최장 일치 구간이 길 수 없다. 일치 블록 합으로 걸러야 한다
    "정기평가는 매년 1회 이상",
])
def test_statute_copy_is_dismissed(claim):
    ev = claim_evidence(claim, CONTEXTS)
    assert ev["verbatim"], f"조문 원문 복사인데 기각되지 않았다: {ev}"


# ── 날조: 조문에 없는 내용을 더했다 → 절대 기각되면 안 된다 ──
#
# 앞의 두 건은 **조문을 거의 그대로 복사하고 숫자만 바꾼 / 결론을 부정으로 뒤집은**
# 문장이다. 글자가 거의 같아 길이·일치율 조건은 통과하므로, 숫자 대조와 부정 대조가
# 각각 유일한 방어선이다. 둘 중 하나를 빼면 이 테스트가 깨진다(mutation test로 확인).
@pytest.mark.parametrize("claim, why", [
    ("제9조를 위반하여 제2조제3호가목의 중대시민재해에 이르게 한 사업주 또는 경영책임자는 "
     "3년 이상의 징역 또는 30억원 이하의 벌금에 처하며, 이 경우 징역과 벌금을 병과할 수 있습니다.",
     "조문을 그대로 복사하고 처벌 수치만 조작 — 숫자 대조만이 막는다"),
    ("제9조를 위반하여 제2조제3호가목의 중대시민재해에 이르게 한 사업주 또는 경영책임자는 "
     "1년 이상의 징역 또는 10억원 이하의 벌금에 처하지 않습니다.",
     "조문을 그대로 복사하고 결론만 부정으로 뒤집음 — 부정 대조만이 막는다"),
    ("경영책임자는 3년 이상의 징역 또는 30억원 이하의 벌금에 처해집니다.", "처벌 수치 조작"),
    ("다만 상시근로자 50명 미만 사업장은 이 조항의 적용에서 제외됩니다.", "없는 적용요건"),
    ("조립을 마친 뒤 48시간 이내에 관할 지방고용노동관서에 신고서를 제출해야 합니다.", "없는 의무"),
])
def test_fabrication_is_not_dismissed(claim, why):
    ev = claim_evidence(claim, CONTEXTS)
    assert not ev["verbatim"], f"날조({why})가 기각됐다 — 탐지력이 죽는다: {ev}"


def test_case_is_adjusted_only_when_every_claim_is_a_copy():
    copy = "정기평가는 매년 1회 이상"
    fake = "법인에게는 별도로 100억원 이하의 벌금이 병과됩니다."

    assert recheck_case("PARTIAL", [copy], CONTEXTS)["adjusted_verdict"] == "GROUNDED"
    # 하나라도 날조면 판정을 유지한다 — 복사 문장에 섞어 넣는 것으로 통과시킬 수 없다
    assert recheck_case("PARTIAL", [copy, fake], CONTEXTS)["adjusted_verdict"] == "PARTIAL"
    # GROUNDED는 손대지 않는다
    assert recheck_case("GROUNDED", [], CONTEXTS)["adjusted_verdict"] == "GROUNDED"
